export function getWilayaCoords(name: string): { lat: number; lng: number } {
  const found = ALGERIA_WILAYAS.find(
    (w) => w.name.toLowerCase() === name.toLowerCase() || name.toLowerCase().includes(w.name.toLowerCase())
  );
  return found ? { lat: found.lat, lng: found.lng } : { lat: 36.7538, lng: 3.0588 };
}
